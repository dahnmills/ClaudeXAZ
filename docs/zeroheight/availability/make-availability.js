// Generates build-availability.js: the Playwright snippet that fills the ZeroHeight page
// "Component availability" from docs/components-status/components.json.
// Usage (repo root): node docs/zeroheight/availability/make-availability.js
// then run build-availability.js with the Playwright MCP (browser_run_code_unsafe, filename).
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '../../..');
const j = require(path.join(root, 'docs/components-status/components.json'));

const FAMILIES = [
  ['action', 'Action'], ['navigation', 'Navigation'], ['data-entry', 'Data Entry'], ['data-display', 'Data Display'],
  ['feedback', 'Feedback'], ['layout', 'Layout'], ['overlay', 'Overlay'], ['other', 'Utilities'],
];
const STATE = { ready: 'Ready', 'in-review': 'In review', draft: 'Draft', deprecated: 'Deprecated' };

// Same component listed twice (e.g. Flyout Menu in action and in overlay): keep the record with a Figma link.
const byName = new Map();
for (const c of j.components.filter((x) => x.category !== 'local')) {
  const prev = byName.get(c.name);
  const score = (x) => (x.figma && x.figma.url ? 2 : 0) + (x.availability.design ? 1 : 0);
  if (!prev || score(c) > score(prev)) byName.set(c.name, c);
}
const dups = j.components.filter((x) => x.category !== 'local').length - byName.size;
if (dups) console.log('duplicates merged:', dups);
const rows = [...byName.values()].map((c) => {
  const fileKey = (c.figma && c.figma.fileKey) || (j.figmaFiles && j.figmaFiles[c.figmaLibrary]) || null;
  const figmaUrl = c.availability.design ? ((c.figma && c.figma.url) || (fileKey ? `https://www.figma.com/design/${fileKey}` : 'yes')) : null;
  return {
    cat: c.category, name: c.name, selector: c.selector,
    state: STATE[c.state] || c.state, version: c.version,
    figma: figmaUrl,
    vibe: c.availability.vibecoded ? (c.storybook && c.storybook.vibecodedUrl) || 'code' : null,
    dev: c.storybook && c.storybook.devUrl ? c.storybook.devUrl : null,
    zh: c.zeroheight && c.zeroheight.url ? c.zeroheight.url : null,
  };
});
const count = (f) => rows.filter(f).length;
const summary = {
  total: rows.length,
  design: count((r) => r.figma), vibe: count((r) => r.vibe), dev: count((r) => r.dev),
  ready: count((r) => r.state === 'Ready'), date: new Date().toISOString().slice(0, 10),
};

const data = JSON.stringify({ FAMILIES, rows, summary });
const out = `// GENERATED by make-availability.js from components.json (${summary.date}). Do not edit by hand.
async (page) => {
  const DATA = ${data};
  await page.goto('https://qirin-design-system.zeroheight.com/styleguide/s/138794/p/' + PAGE_ID);
  await page.waitForSelector('.ProseMirror');
  await page.waitForTimeout(3000);
  return await page.evaluate((DATA) => {
    // ZeroHeight page of each component, found in the navigation (name -> /p/<id6>)
    const nav = {};
    document.querySelectorAll('a[href*="/p/"]').forEach((a) => {
      const m = a.getAttribute('href').match(/\\/p\\/([0-9a-f]{6})-[^/]*$/);
      if (m) { const n = a.textContent.trim().toLowerCase(); if (!nav[n]) nav[n] = 'https://qirin-design-system.zeroheight.com/styleguide/s/138794/p/' + m[1]; }
    });
    const id = () => Math.random().toString(16).slice(2, 12).padEnd(10, '0');
    const t = (text, marks) => (marks ? { type: 'text', text, marks } : { type: 'text', text });
    const b = (text) => t(text, [{ type: 'strong', attrs: { blockId: '' } }]);
    const a = (text, href) => t(text, [{ type: 'link', attrs: { blockId: '', href, target: '_blank', rel: 'noopener noreferrer nofollow', class: 'zheditor-a' } }]);
    const p = (...c) => ({ type: 'paragraph', attrs: { blockId: id() }, content: c.filter(Boolean) });
    const h = (level, text) => ({ type: 'heading', attrs: { blockId: id(), level }, content: [t(text)] });
    const cell = (content, w) => ({ type: 'tableCell', attrs: { blockId: '', colspan: 1, rowspan: 1, colwidth: w ? [w] : null, verticalTextAlignment: null, horizontalTextAlignment: null }, content: [p(...content)] });
    const W = [190, 120, 110, 120, 120, 120];
    const row = (cells) => ({ type: 'tableRow', attrs: { blockId: '' }, content: cells.map((c, i) => cell(c, W[i])) });
    const table = (rows) => ({ type: 'table', attrs: { blockId: id(), displayBorders: true, showHeader: true, stickyHeader: false, fullWidth: false, showRowBackground: false, borderStyle: 'full', horizontalTextAlignment: 'left', verticalTextAlignment: 'center' }, content: rows });
    const DASH = [t('\\u2014')];
    const S = DATA.summary;

    const body = [
      p(t('Where each component stands today, on each side. Every row links to the place where you use it.')),
      { type: 'bulletList', attrs: { blockId: id() }, content: [
        [b('Design'), t(': the component exists in a Qirin Figma library. The link opens it in Figma.')],
        [b('Vibecode'), t(': the component is coded in the Qirin prototype (Angular, standalone, signal inputs). The link opens its Storybook page.')],
        [b('Dev'), t(': the production implementation by the development team. Planned: not delivered yet.')],
        [b('Guidelines'), t(': the usage page on ZeroHeight.')],
      ].map((c) => ({ type: 'listItem', attrs: { blockId: '' }, content: [p(...c)] })) },
      { type: 'callout', attrs: { blockId: id(), type: 'calloutBackground2', fullWidth: true }, content: [p(
        b(S.total + ' components. '),
        t(S.design + ' in Figma, ' + S.vibe + ' vibecoded, ' + S.dev + ' in production code. ' + S.ready + ' are Ready. Updated ' + S.date + ' from the component status file.'),
      )] },
      p(b('Status'), t(': Ready = Figma, code, Storybook and guidelines all exist. In review = code and Storybook exist, Figma or guidelines still missing. Draft = anything less.')),
    ];

    for (const [cat, label] of DATA.FAMILIES) {
      const list = DATA.rows.filter((r) => r.cat === cat);
      if (!list.length) continue;
      body.push(h(2, label + ' (' + list.length + ')'));
      const rows = [row([[b('Component')], [b('Status')], [b('Design')], [b('Vibecode')], [b('Dev')], [b('Guidelines')]])];
      for (const r of list) {
        const zh = r.zh || nav[r.name.toLowerCase()] || null;
        rows.push(row([
          [t(r.name)],
          [t(r.state + ', ' + r.version)],
          r.figma ? (r.figma === 'yes' ? [t('In Figma')] : [a('Figma', r.figma)]) : DASH,
          r.vibe ? (r.vibe === 'code' ? [t('Coded')] : [a('Storybook', r.vibe)]) : DASH,
          r.dev ? [a('Storybook', r.dev)] : [t('Planned')],
          zh ? [a('ZeroHeight', zh)] : DASH,
        ]));
      }
      body.push(table(rows));
    }

    const eds = document.querySelectorAll('.ProseMirror');
    eds[0].editor.chain().setContent({ type: 'doc', content: [p(t('What is up to date and available in Design, in Vibecode and in Dev, with a direct link for every component.'))] }).run();
    eds[1].editor.chain().setContent({ type: 'doc', content: body }).run();
    const n = eds[1].editor.getJSON().content;
    return n.length + ' blocks, ' + n.filter((x) => x.type === 'table').length + ' tables, ZH links found in nav: ' + Object.keys(nav).length;
  }, DATA);
}
`;
fs.writeFileSync(path.join(__dirname, 'build-availability.js'), out.replace('PAGE_ID', JSON.stringify(process.argv[2] || 'PAGE_ID_MISSING')));
console.log('written', summary);
